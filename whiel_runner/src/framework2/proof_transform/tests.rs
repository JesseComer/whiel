use super::*;

/// One complete emitted proof carrying the pinned global
/// `prenexify`/`cnfify` package, lifted verbatim out of
/// `Benchmark/Example0001/Certificate/VampireArtifacts/jobs/maint_clause_0/leancheck.lean`
/// (step 19 and its seven targets) around a minimal module frame. It
/// spells the import `VampLean.Runtime` so the legacy Python's own
/// canonicalization is the identity on it and the two implementations'
/// outputs are directly comparable; the emitter's `import VampLean`
/// spelling is equally accepted (see [`accepts_either_pinned_import`]).
const PROJECTION_INPUT: &str = include_str!("fixtures/projection_input.lean");
/// The legacy `rewrite_vamplean_projection_blocks` output on
/// [`PROJECTION_INPUT`], generated from `whiel_synth` and checked in as
/// the differential-parity reference.
const PROJECTION_REWRITTEN: &str = include_str!("fixtures/projection_rewritten.lean");

const JOB: &str = "maint_clause_0";

/// The kernel-SAT context these fixtures run under. Every one of them is a
/// `direct`-profile proof with no AVATAR refutation in it, so the step is
/// a recorded miss and the solver is never asked for a trace; a recorded
/// solver with no traces therefore stands in for the pinned CaDiCaL, and
/// would fail loudly if a fixture ever did carry a helper.
fn kernel_sat_context() -> lrat::RecordedLratSolver {
    lrat::RecordedLratSolver::new(Vec::new())
}

fn cadical_identity() -> serde_json::Value {
    serde_json::json!({ "kind": "test_recorded_lrat_solver" })
}

fn transformed(raw: &str) -> TransformedProof {
    let solver = kernel_sat_context();
    let context = KernelSatContext::new(&solver, cadical_identity());
    apply_proof_transforms(JOB, raw, &context).expect("the fixture is a recognized proof shape")
}

fn projection_record(proof: &TransformedProof) -> &ProofTransformRecord {
    proof
        .transforms
        .iter()
        .find(|record| record.id == ProofTransformId::ClauseProjection)
        .expect("the projection step always runs")
}

