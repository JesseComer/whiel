#[test]
fn chains_the_recorded_digests_across_the_fixed_order() {
    let proof = transformed(PROJECTION_INPUT);
    assert_eq!(proof.transforms.len(), TRANSFORM_ORDER.len());
    for (record, id) in proof.transforms.iter().zip(TRANSFORM_ORDER) {
        assert_eq!(record.id, id);
        assert_eq!(record.version, id.version());
    }
    // The kernel-SAT step sits between the canonical form and the two
    // optional rewrites, and misses on this fixture, so the projection is
    // handed the canonical text and its output is the final text.
    assert_eq!(proof.transforms[1].input_sha256, proof.canonical_sha256);
    assert_eq!(proof.transforms[2].input_sha256, proof.canonical_sha256);
    assert_eq!(proof.transforms[2].output_sha256, proof.transformed_sha256);
    assert!(proof.rewritten());
}

#[test]
fn a_compile_gate_fallback_records_only_the_rewrites_it_gave_up() {
    let proof = transformed(PROJECTION_INPUT);
    let candidate = proof
        .fallback_candidates
        .first()
        .expect("a projected proof has something to retreat to");
    assert_eq!(candidate.dropped, vec![ProofTransformId::ClauseProjection]);
    let mut records = proof.transforms.clone();
    mark_rolled_back(&mut records, &candidate.dropped);
    // The canonical step itself is never rolled back: it is what every
    // candidate is built on. (It reports a miss on this fixture because
    // the fixture is already canonical.)
    assert_eq!(records[0].outcome, ProofTransformOutcome::Miss);
    let projection = records
        .iter()
        .find(|record| record.id == ProofTransformId::ClauseProjection)
        .expect("the projection step ran");
    let rendered = projection.to_json();
    assert_eq!(rendered["outcome"], "fallback");
    assert_eq!(rendered["id"], "clause_projection");
    // A rolled-back step still names the candidate it produced, so the
    // receipt records what was tried as well as what was kept.
    assert_eq!(rendered["output_sha256"], proof.transformed_sha256);
    // Nothing else moved: a step that missed did not become a rollback.
    for record in &records {
        if record.id != ProofTransformId::ClauseProjection {
            assert_ne!(record.outcome, ProofTransformOutcome::Fallback);
        }
    }
}

