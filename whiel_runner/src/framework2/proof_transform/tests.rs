#[test]
fn a_rejected_prenex_slice_returns_to_the_projected_text_not_the_canonical_one() {
    // The chain gives up one optional rewrite at a time, so a slice the
    // compile gate rejects costs the slice and nothing else: the
    // projection stands, and the receipt says so.
    let proof = prenex_transformed(PRENEX_INPUT);
    let candidate = proof
        .fallback_candidates
        .first()
        .expect("the projected proof is the first thing to retreat to");
    assert_eq!(candidate.dropped, vec![ProofTransformId::LocalPrenex]);

    let mut records = proof.transforms.clone();
    mark_rolled_back(&mut records, &candidate.dropped);
    let outcome = |id| {
        records
            .iter()
            .find(|record| record.id == id)
            .expect("every step is recorded")
            .outcome
    };
    assert_eq!(
        outcome(ProofTransformId::Canonical),
        ProofTransformOutcome::Miss
    );
    assert_eq!(
        outcome(ProofTransformId::ClauseProjection),
        ProofTransformOutcome::Applied
    );
    assert_eq!(
        outcome(ProofTransformId::LocalPrenex),
        ProofTransformOutcome::Fallback
    );
    // The rolled-back row still names the candidate it produced.
    let slice = records
        .iter()
        .find(|record| record.id == ProofTransformId::LocalPrenex)
        .expect("the slice step ran");
    assert_eq!(slice.output_sha256, proof.transformed_sha256);
}

#[test]
fn chains_the_recorded_digests_through_the_local_prenex_step() {
    let proof = prenex_transformed(PRENEX_INPUT);
    assert_eq!(proof.transforms.len(), TRANSFORM_ORDER.len());
    // The slice step is last, so it is handed the projection's output and
    // its own output is the text that gets packaged.
    assert_eq!(proof.transforms[3].id, ProofTransformId::LocalPrenex);
    assert_eq!(
        proof.transforms[2].output_sha256,
        proof.transforms[3].input_sha256
    );
    assert_eq!(proof.transforms[3].output_sha256, proof.transformed_sha256);
    assert_ne!(
        proof.transforms[3].input_sha256,
        proof.transforms[3].output_sha256
    );
}

