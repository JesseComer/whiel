fn prenex_transformed(raw: &str) -> TransformedProof {
    let solver = kernel_sat_context();
    let context = KernelSatContext::new(&solver, cadical_identity());
    apply_proof_transforms(PRENEX_JOB, raw, &context)
        .expect("the fixture is a recognized proof shape")
}

fn prenex_refusal(raw: &str) -> String {
    let solver = kernel_sat_context();
    let context = KernelSatContext::new(&solver, cadical_identity());
    apply_proof_transforms(PRENEX_JOB, raw, &context)
        .expect_err("the mutated fixture must be refused")
        .message
}

fn prenex_record(proof: &TransformedProof) -> &ProofTransformRecord {
    proof
        .transforms
        .iter()
        .find(|record| record.id == ProofTransformId::LocalPrenex)
        .expect("the local-prenex step always runs")
}

/// The receipt's miss reasons, in order.
fn prenex_misses(record: &ProofTransformRecord) -> Vec<String> {
    record.detail["missed"]
        .as_array()
        .expect("the receipt always carries a miss list")
        .iter()
        .map(|entry| format!("{}:{}", entry["step_id"], entry["reason"].as_str().unwrap()))
        .collect()
}

