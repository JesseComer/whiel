#[test]
fn no_candidate_of_an_avatar_job_reintroduces_bv_decide() {
    // The canonical text of an AVATAR job still closes its Boolean helper
    // by `bv_decide`, so retreating to it would publish a native-runtime
    // reconstruction. The chain therefore stops above the kernel-SAT
    // step: this proof rewrites nothing else, so it has no candidate at
    // all and such a job fails its build instead.
    let solver = avatar_solver();
    let proof = avatar_pipeline(&raw_proof(AVATAR_BLOCK), &solver).unwrap();
    assert!(proof.rewritten());
    assert!(proof.kernel_sat_applied());
    assert!(proof.fallback_candidates.is_empty());
    for candidate in &proof.fallback_candidates {
        assert!(!candidate.text.contains("bv_decide"));
        assert!(
            !candidate
                .dropped
                .contains(&ProofTransformId::AvatarKernelSat)
        );
    }

    // A job the kernel-SAT step missed keeps the ordinary chain down to
    // the canonical text.
    let projected = transformed(PROJECTION_INPUT);
    assert!(projected.rewritten());
    assert!(!projected.kernel_sat_applied());
    assert_eq!(
        projected.fallback_candidates.last().map(|c| &c.sha256),
        Some(&projected.canonical_sha256)
    );
}

#[test]
fn a_rat_bearing_trace_fails_the_job_with_its_recorded_reason() {
    // A RAT step is well-formed evidence outside the accepted RUP-only
    // fragment. It is never a silent skip: the job fails, naming why, and
    // the emitted `bv_decide` reconstruction is not published in its place.
    // The captured block's own trace with a RAT group appended to the
    // first addition's hints: well formed, outside the accepted fragment.
    let solver = lrat::RecordedLratSolver::new(vec![(
        199,
        "5 -1 0 2 3 -1 2 0\n6 2 0 5 1 0\n7 0 6 4 0\n".to_string(),
    )]);
    let error = avatar_pipeline(&raw_proof(AVATAR_BLOCK), &solver)
        .expect_err("a RAT-bearing trace is refused");
    assert_eq!(error.transform, ProofTransformId::AvatarKernelSat);
    assert_eq!(error.job_id, AVATAR_JOB);
    assert!(
        error.message.contains("RUP-only fragment"),
        "{}",
        error.message
    );
    assert!(
        error.message.contains("may not be published"),
        "{}",
        error.message
    );
}

