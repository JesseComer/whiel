#[test]
fn normalize_telescope_order_sorts_names_and_groups_and_nothing_else() {
    let source = "variable {«_sK9» «_sK7» «_sK8» :  ι → ι}\n  {«_sP1» «_sP0» :  ι → Prop}\n\
                  theorem t : True := trivial\n";
    assert_eq!(
        canonical::normalize_telescope_order(source),
        "variable {«_sK7» «_sK8» «_sK9» : ι → ι}\n  {«_sP0» «_sP1» : ι → Prop}\n\
         theorem t : True := trivial\n"
    );
    // Two spellings of one telescope agree after normalization, and a
    // module with no telescope is returned unchanged.
    let permuted = "variable {«_sP1» «_sP0» :  ι → Prop}\n  {«_sK8» «_sK9» «_sK7» :  ι → ι}\n\
                    theorem t : True := trivial\n";
    assert_eq!(
        canonical::normalize_telescope_order(source),
        canonical::normalize_telescope_order(permuted)
    );
    // A module with no quoted binder group comes back byte for byte, so
    // the comparison digest ignores telescope order and nothing else.
    assert_eq!(
        canonical::normalize_telescope_order(PROJECTION_REWRITTEN),
        PROJECTION_REWRITTEN
    );
}

#[test]
fn telescope_comparison_preserves_non_variable_binders_comments_and_strings() {
    for source in [
        "-- documented binder {«z» «a» : ι}\n",
        "def example : String := \"{«z» «a» : ι}\"\n",
        "theorem chooses_second {«z» «a» : ι} : «a» = «a» := rfl\n",
        "/-\nvariable {«z» «a» : ι}\n  {«c» «b» : Prop}\n-/\n",
        "def example : String := \"\nvariable {«z» «a» : ι}\n\"\n",
        "def example := `(command|\nvariable {«z» «a» : ι}\n)\n",
        "variable {«z» «a» : ι} -- an unrecognized annotated layout\n",
        "variable {«z» «a» : ι} {«c» «b» : Prop}\n",
        "variable {«z» «a» : Nat}\n",
        "variable {«z odd» «z» «a» : ι}\n",
        "variable {«z--» «z» «a» : ι}\n",
        "variable {«z» «a» : «earlier» → Prop}\n",
        "/- unterminated\nvariable {«z» «a» : ι}\n",
    ] {
        assert_eq!(canonical::normalize_telescope_order(source), source);
        let changed = source.replace("«z» «a»", "«a» «z»");
        assert_ne!(
            canonical::normalize_telescope_order(source),
            canonical::normalize_telescope_order(&changed),
            "comparison must retain a change outside the generated telescope: {source}"
        );
    }
}
