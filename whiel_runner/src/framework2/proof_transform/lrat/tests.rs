#[test]
fn plans_the_captured_avatar_shape() {
    let problems = plan_avatar_kernel_sat(&raw_proof(AVATAR_BLOCK), "init_clause_0").unwrap();
    assert_eq!(problems.len(), 1);
    let problem = &problems[0];
    assert_eq!(problem.step_id, 199);
    assert_eq!(problem.kind, AvatarKind::Sat);
    assert_eq!(problem.variable_ids, vec![2, 3, 15]);
    assert_eq!(
        problem.clauses,
        vec![
            vec![(2, true), (3, true)],
            vec![(15, true)],
            vec![(2, false), (15, false)],
            vec![(3, false)],
        ]
    );
    assert_eq!(problem.cnf_source, EXPECTED_DIMACS);
}

#[test]
fn prepared_traces_require_the_exact_cnf_and_step() {
    let problem = plan_avatar_kernel_sat(&raw_proof(AVATAR_BLOCK), "init_clause_0")
        .unwrap()
        .remove(0);
    let solver = PreparedLratSolver::new(vec![(problem.clone(), LRAT_TRACE.to_string())]);
    assert_eq!(
        solver.refute(problem.step_id, &problem.cnf_source).unwrap(),
        LRAT_TRACE
    );
    assert!(
        solver
            .refute(problem.step_id + 1, &problem.cnf_source)
            .is_err()
    );
    assert!(solver.refute(problem.step_id, "p cnf 0 0\n").is_err());
}

