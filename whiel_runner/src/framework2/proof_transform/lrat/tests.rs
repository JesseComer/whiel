/// A scratch root holding a fake `cadical` that runs `script`, and a solver
/// pointed at it.
///
/// Modelled on the lock reader's fake-binary fixtures in `leancheck.rs`:
/// the exit-code contract is this seam's whole decision, so it is exercised
/// against a scripted binary rather than the pinned one. The script sees the
/// DIMACS path as `$1` and the trace path it is expected to write as `$2`.
fn fake_cadical(label: &str, script: &str) -> (PathBuf, CadicalLratSolver) {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = std::env::temp_dir().join(format!(
        "whiel_lrat_cadical_{label}_{}_{nanos}",
        std::process::id()
    ));
    std::fs::create_dir_all(&root).unwrap();
    let executable = root.join("cadical");
    std::fs::write(&executable, script).unwrap();
    let mut permissions = std::fs::metadata(&executable).unwrap().permissions();
    permissions.set_mode(0o755);
    std::fs::set_permissions(&executable, permissions).unwrap();
    let solver = CadicalLratSolver::new(executable, vec!["--lrat".to_string()], root.join("work"));
    (root, solver)
}

#[test]
