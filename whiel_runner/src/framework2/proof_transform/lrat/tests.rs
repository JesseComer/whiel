#[test]
fn rewrites_the_captured_block_exactly_as_the_legacy_python_does() {
    let outcome = transform(&raw_proof(AVATAR_BLOCK)).unwrap();
    assert_eq!(outcome.outcome, KernelSatOutcome::Applied);
    assert!(outcome.text.contains(EXPECTED_BLOCK));
    assert!(!outcome.text.contains("bv_decide"));
    assert!(outcome.requires_from_lrat_import());

    let helper = &outcome.helpers[0];
    assert_eq!(helper.lrat_source, LRAT_TRACE);
    assert_eq!(helper.lrat_additions, 3);
    assert_eq!(helper.lrat_deletions, 1);
    assert_eq!(helper.lrat_max_clause_id, 7);
}

#[test]
fn the_rewritten_proof_asks_for_the_import_rather_than_writing_it() {
    // `packageProof` takes the extra import as a payload and inserts it
    // after its own `import VampLean`, so the rewritten text must carry no
    // import line of its own.
    let outcome = transform(&raw_proof(AVATAR_BLOCK)).unwrap();
    assert!(outcome.requires_from_lrat_import());
    assert!(!outcome.text.contains(&format!("import {FROM_LRAT_IMPORT}")));
    assert_eq!(
        outcome
            .text
            .split('\n')
            .filter(|line| line.trim_start().starts_with("import "))
            .collect::<Vec<_>>(),
        ["import VampLean"]
    );
}

#[test]
fn the_probe_declares_and_audits_every_helper_in_isolation() {
    let outcome = transform(&raw_proof(AVATAR_BLOCK)).unwrap();
    let probe = outcome.probe_source.unwrap();
    assert!(probe.starts_with(&format!("import {FROM_LRAT_IMPORT}")));
    assert!(probe.contains("namespace KernelSatStep199"));
    assert!(probe.contains("variable (sA2 sA3 sA15 : Prop)"));
    assert!(probe.contains("#print axioms inf_s199_lrat"));
    assert!(probe.contains("#print axioms inf_s199"));
    assert!(probe.contains(EXPECTED_BLOCK));
}

#[test]
fn an_already_rewritten_proof_is_returned_unchanged() {
    let first = transform(&raw_proof(AVATAR_BLOCK)).unwrap();
    // The solver must never be consulted again: an empty recording would
    // fail if it were.
    let solver = RecordedLratSolver::new(Vec::new());
    let second = transform_avatar_kernel_sat(&first.text, "init_clause_0", &solver).unwrap();
    assert_eq!(second.outcome, KernelSatOutcome::AlreadyApplied);
    assert_eq!(second.text, first.text);
    assert_eq!(second.helpers, first.helpers);
}

