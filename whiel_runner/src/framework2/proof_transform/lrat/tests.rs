#[test]
fn concurrent_same_step_calls_read_only_their_own_input_and_trace() {
    let (root, solver) = fake_cadical(
        "same-step",
        r#"#!/bin/sh
root=$(dirname "$0")
printf '%s\n' "$PWD" >> "$root/started"
while [ ! -e "$root/release" ]; do sleep 0.01; done
cat "$1" > "$2"
exit 20
"#,
    );
    let solver = std::sync::Arc::new(solver);
    let threads: Vec<_> = ["first CNF\n", "second CNF\n"]
        .into_iter()
        .map(|input| {
            let solver = solver.clone();
            std::thread::spawn(move || (input, solver.refute(199, input)))
        })
        .collect();
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(10);
    let count = loop {
        let count = std::fs::read_to_string(root.join("started"))
            .unwrap_or_default()
            .lines()
            .count();
        if count == 2 || std::time::Instant::now() >= deadline {
            break count;
        }
        std::thread::sleep(std::time::Duration::from_millis(5));
    };
    // Release even on a timeout so failed assertions cannot strand a child.
    std::fs::write(root.join("release"), b"go").unwrap();
    let results: Vec<_> = threads
        .into_iter()
        .map(|thread| thread.join().unwrap())
        .collect();
    assert_eq!(count, 2, "both children reached the controlled overlap");
    for (input, result) in results {
        assert_eq!(result.unwrap(), input);
    }
    let started = std::fs::read_to_string(root.join("started")).unwrap();
    let directories: std::collections::BTreeSet<_> = started.lines().collect();
    assert_eq!(directories.len(), 2);
    for directory in directories {
        assert_eq!(
            std::fs::read(Path::new(directory).join("input.cnf")).unwrap(),
            std::fs::read(Path::new(directory).join("proof.lrat")).unwrap()
        );
    }
    std::fs::remove_dir_all(root).unwrap();
}

#[test]
fn repeated_step_retains_prior_evidence_and_cannot_reuse_a_stale_trace() {
    let (root, solver) = fake_cadical(
        "repeat-step",
        r#"#!/bin/sh
if [ "$(cat "$1")" = "good" ]; then printf 'good trace\n' > "$2"; fi
exit 20
"#,
    );
    assert_eq!(solver.refute(199, "good\n").unwrap(), "good trace\n");
    let first = std::fs::read_dir(root.join("work"))
        .unwrap()
        .next()
        .unwrap()
        .unwrap()
        .path();
    assert!(solver.refute(199, "bad\n").is_err());
    assert_eq!(
        std::fs::read_to_string(first.join("input.cnf")).unwrap(),
        "good\n"
    );
    assert_eq!(
        std::fs::read_to_string(first.join("proof.lrat")).unwrap(),
        "good trace\n"
    );
    assert_eq!(solver.refute(199, "good\n").unwrap(), "good trace\n");
    assert_eq!(std::fs::read_dir(root.join("work")).unwrap().count(), 3);
    std::fs::remove_dir_all(root).unwrap();
}
