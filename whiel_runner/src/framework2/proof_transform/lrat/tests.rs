//! Unit tests for the AVATAR kernel-SAT rewrite.
//!
//! The fixture is the captured `casc_2025` AVATAR block of an
//! `init_clause_0` leancheck run, trailing emitter whitespace included, so
//! the pinned shape is exercised exactly as the emitter prints it. The
//! expected rewritten block and the LRAT trace below are the legacy
//! Python's own output for that block (differential parity fixture:
//! `rewrite_avatar_kernel_sat` plus the pinned CaDiCaL).

use super::*;
use std::os::unix::fs::PermissionsExt;
use std::time::{SystemTime, UNIX_EPOCH};

/// The captured AVATAR block, byte for byte. Note the trailing space the
/// emitter leaves after the `have satProof :=` application.
pub(crate) const AVATAR_BLOCK: &str = concat!(
    "-- step 199 avatar sat refutation\n",
    "set_option maxHeartbeats 200000000 in\n",
    "-- this is probably due to a suboptimal encoding\n",
    "theorem inf_s199' (sA2' sA3' sA15' : Bool) : (sA2' || sA3') → (sA15') → \
     (!sA2' || !sA15') → (!sA3') → False := by\n",
    "  intro h\n",
    "  bv_decide\n",
    "\n",
    "theorem inf_s199 : (sA2 ∨ sA3) → (sA15) → ((¬sA2) ∨ (¬sA15)) → ((¬sA3)) → False := by\n",
    "  classical\n",
    "  have satProof := inf_s199' (decide sA2) (decide sA3) (decide sA15) \n",
    "  rewrite_decide_eq [sA2 sA3 sA15 ]\n",
    "  sat_norm\n",
    "  exact satProof\n",
);

/// The trace the pinned CaDiCaL produces for this block's DIMACS.
pub(crate) const LRAT_TRACE: &str = "5 -1 0 2 3 0\n5 d 3 0\n6 2 0 5 1 0\n7 0 6 4 0\n";

const EXPECTED_DIMACS: &str = "p cnf 3 4\n1 2 0\n3 0\n-1 -3 0\n-2 0\n";

/// The legacy Python's rendered replacement, byte for byte.
const EXPECTED_BLOCK: &str = concat!(
    "-- step 199 avatar sat refutation via kernel-checked LRAT\n",
    "lrat_proof inf_s199_lrat\n",
    "  \"p cnf 3 4\\n1 2 0\\n3 0\\n-1 -3 0\\n-2 0\\n\"\n",
    "  \"5 -1 0 2 3 0\\n5 d 3 0\\n6 2 0 5 1 0\\n7 0 6 4 0\\n\"\n",
    "\n",
    "theorem inf_s199 : (sA2 ∨ sA3) → (sA15) → ((¬sA2) ∨ (¬sA15)) → ((¬sA3)) → False := by\n",
    "  intro h1 h2 h3 h4\n",
    "  have h := inf_s199_lrat sA2 sA3 sA15\n",
    "  exact (fun hs => Or.elim hs (fun hs => Or.elim hs (fun hf => Or.elim h1 hf.1 \
     (fun hr => hf.2 hr)) (fun hf => hf h2)) (fun hs => Or.elim hs (fun hf => Or.elim h3 \
     (fun hn => hn hf.1) (fun hr => (fun hn => hn hf.2) hr)) (fun hf => (fun hn => hn hf) h4))) h\n",
);

/// A whole raw leancheck proof around `body`, in the emitted shape.
pub(crate) fn raw_proof(body: &str) -> String {
    format!(
        concat!(
            "-- Lean proof output generated by Vampire\n",
            "import VampLean\n",
            "section vamproof\n",
            "universe u\n",
            "set_option maxHeartbeats 0\n",
            "set_option maxRecDepth 100000000\n",
            "variable {{sA2 sA3 sA15 : Prop}}\n",
            "\n",
            "{}",
            "\n",
            "theorem fullProof : True := by\n",
            "  trivial\n",
            "\n",
            "end vamproof\n",
        ),
        body
    )
}

fn recorded() -> RecordedLratSolver {
    RecordedLratSolver::new(vec![(199, LRAT_TRACE.to_string())])
}

fn transform(raw: &str) -> Result<KernelSatTransform, KernelSatError> {
    transform_avatar_kernel_sat(raw, "init_clause_0", &recorded())
}

