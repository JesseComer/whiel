def build_sheets(records: list[dict]) -> None:
    tags = list(VOCAB.keys())
    header = ["id", "title", "category", "family", "kind", "status", "expectation", "notation", "tags", "sources"] + tags
    rows = []
    for r in records:
        rows.append([r["id"], r["title"], r["category_key"], r["family"], r["kind"], r["status"], r["expectation"],
                     r["notation"], ", ".join(r["tags"]),
                     " | ".join((s["url"] or s["label"]) for s in r["sources"])] + ["x" if t in r["tags"] else "" for t in tags])
    with (HERE / "benchmark_tags.csv").open("w", newline="\n", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter
    except ImportError:
        print("openpyxl missing: only the CSV was written")
        return
    wb = Workbook()
    ws = wb.active
    ws.title = "cases"
    ws.append(header)
    for row in rows:
        ws.append(row)
    fixed = 10  # id … sources; the tag columns follow
    for c in ws[1]:
        c.font = Font(bold=True)
        c.alignment = Alignment(text_rotation=90 if c.column > fixed else 0, vertical="bottom", wrap_text=True)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(header))}{len(rows) + 1}"
    widths = [12, 60, 16, 24, 30, 18, 16, 10, 50, 50]
    for i, wdt in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = wdt
    for i in range(fixed + 1, len(header) + 1):
        ws.column_dimensions[get_column_letter(i)].width = 3.2
    ws.row_dimensions[1].height = 120
    for row in ws.iter_rows(min_row=2, min_col=fixed + 1):
        for c in row:
            if c.value == "x":
                c.fill = PatternFill("solid", fgColor="D6E4F0")
                c.alignment = Alignment(horizontal="center")
    wt = wb.create_sheet("tags")
    wt.append(["tag", "group", "assigned", "count", "description"])
    count = Counter(t for r in records for t in r["tags"])
    for tag, info in VOCAB.items():
        wt.append([tag, info["group"], "auto" if info["auto"] else "manual", count[tag], info["description"]])
    for c in wt[1]:
        c.font = Font(bold=True)
    wt.column_dimensions["A"].width = 24
    wt.column_dimensions["E"].width = 120
    wh = wb.create_sheet("how-to-filter")
    for line in ["Sheet 'cases': one row per case, one column per tag ('x' = tag holds).",
                 "To select the cases carrying several tags: use the AutoFilter on the header row and choose 'x' in each of those tag columns (the filters combine with AND).",
                 "Column 'tags' lists all tags of a case; column 'sources' the source links.",
                 "Column 'status' is read off the case folder; column 'expectation' is what its metadata expects.",
                 f"Generated by {REPORT_LABEL}/build_report.py from {REPORT_LABEL}/tags.json and curated.json."]:
        wh.append([line])
    wh.column_dimensions["A"].width = 140
    wb.save(HERE / "benchmark_tags.xlsx")


