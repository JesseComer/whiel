def prophecy_note(case: str, meta: dict) -> str:
    ps = CURATED["prophecy_status"]
    if case in ps["established"]:
        return ("established: valid with an axiom-free kernel proof; no quantifier-free inductive invariant over the "
                "program schema is known (conjecture); discharged in the leveled framework at prover level with a "
                "hand-written leveled candidate.")
    if case in ps["certified_framework_ii"]:
        return "kernel-checked certificate with a level-1 prophecy clause (Certificate/Valid.lean, Core.json)."
    if case in ps["solved_framework_ii"]:
        return ("accepted invariant with a prophecy clause above level zero (Core.json); no certificate "
                "built from it yet.")
    if case in ps["expected"]:
        oe = meta.get("obstructionExpectation")
        return "expected, not yet run through the leveled framework" + (f": {oe}" if oe else ".")
    oe = meta.get("obstructionExpectation")
    if oe:
        return f"from the metadata: {oe}"
    return ""


