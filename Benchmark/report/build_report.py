def rule_atoms(rule: str) -> tuple[str | None, list[tuple[str, bool]]]:
    """Head predicate and [(body predicate, negated)] for one rule (any of the syntaxes)."""
    r = rule.strip().rstrip(".").rstrip(";")
    if ":-" in r:
        head, body = r.split(":-", 1)
    else:
        head, body = r, ""
    hm = re.search(r"([A-Za-z_↑][\w↑]*)\s*\(", head)
    hp = hm.group(1) if hm else None
    atoms = []
    for m in re.finditer(r"(!|not\s+|¬\s*)?([A-Za-z_↑][\w↑]*)\s*\(", body):
        atoms.append((m.group(2), bool(m.group(1))))
    return hp, atoms


def analyze_rules(rules: list[str]) -> dict:
    heads = set()
    parsed = []
    for r in rules:
        hp, atoms = rule_atoms(r)
        if hp:
            heads.add(hp)
            parsed.append((hp, atoms))
    negation = any(neg for _, atoms in parsed for _, neg in atoms)
    inequality = any(re.search(r"!=|≠", r) for r in rules)
    # recursion graph among heads
    graph: dict[str, set[str]] = defaultdict(set)
    for hp, atoms in parsed:
        for p, neg in atoms:
            if p in heads and not neg:
                graph[hp].add(p)
    # reachability for cycles
    def reaches(a: str, b: str) -> bool:
        seen, stack = set(), [a]
        while stack:
            x = stack.pop()
            for y in graph.get(x, ()):
                if y == b:
                    return True
                if y not in seen:
                    seen.add(y)
                    stack.append(y)
        return False
    recursive = {h for h in heads if reaches(h, h)}
    mutual = any(a != b and reaches(a, b) and reaches(b, a) for a in recursive for b in recursive)
    nonlinear = False
    for hp, atoms in parsed:
        if hp in recursive:
            n = sum(1 for p, neg in atoms if not neg and p in recursive and reaches(hp, p) and reaches(p, hp))
            if n >= 2:
                nonlinear = True
    return {"negation": negation, "inequality": inequality, "mutual": mutual, "nonlinear": nonlinear,
            "heads": sorted(heads), "recursive": sorted(recursive)}


def collect_datalog(case: str, meta: dict) -> list[dict]:
    """List of blocks: {label, text, provenance} in display order.

    The programs a case records live in its own Metadata.json, under `datalog`; the
    hand-written readings of the loops that have no recorded program live in curated.json,
    under `datalog_overrides`, and are shown after them. Nothing else is read: no fidelity
    module, no tool folder, no .dl file, no inventory of another report.
    """
    blocks: list[dict] = []
    for b in meta.get("datalog") or []:
        block = {"label": b["label"], "text": b["text"], "provenance": b["provenance"]}
        if b.get("source_file"):
            block["source_file"] = b["source_file"]
        blocks.append(block)
    for o in CURATED["datalog_overrides"].get(case, []):
        blocks.append({"label": o["label"], "text": o["text"], "provenance": "hand-written reading (this report)",
                       "source_file": f"{REPORT_LABEL}/curated.json"})
    return blocks


