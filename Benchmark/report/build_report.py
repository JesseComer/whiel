def canon_text(text: str, arities: dict[str, int], order: dict[str, str] | None = None) -> str:
    if order is None:
        order = {}
    s = re.sub(r"∅\[\d+\]", "∅", text)
    s = re.sub(r"¬\s*\(\s*(\w+)\s*=\s*(\w+)\s*\)", r"\1 ≠ \2", s)
    s = re.sub(r"_(aux|2)\b", "_s", s)
    s = re.sub(r"WHILE \((.*)\) DO", r"WHILE \1 DO", s)

    def rep(m):
        w = m.group(0)
        snap = w.endswith("_s")
        base = w[:-2] if snap else w
        if base not in arities:
            return w
        if base not in order:
            order[base] = f"r{len(order)}"
        return order[base] + ("_s" if snap else "")
    s = IDENT.sub(rep, s)
    # drop one pair of parentheses around a whole right-hand side
    s = re.sub(r":=\s*\((.*)\)\s*(;|$)", lambda m: ":=" + m.group(1) + m.group(2), s, flags=re.M)
    return re.sub(r"\s+", "", s)


def canon_rules(rules: list[str]) -> str:
    preds: dict[str, str] = {}
    out = []
    for r in rules:
        r2 = r.strip().rstrip(".").rstrip(";")
        vars_: dict[str, str] = {}

        def rp(m):
            p = m.group(1)
            if p not in preds:
                preds[p] = f"p{len(preds)}"
            return preds[p] + "("
        r2 = re.sub(r"([A-Za-z_↑][\w↑]*)\s*\(", rp, r2)

        def rv(m):
            v = m.group(0)
            if v not in vars_:
                vars_[v] = f"v{len(vars_)}"
            return vars_[v]
        r2 = re.sub(r"(?<=[(,\s])([A-Za-z_][\w]*)(?=[,)\s])", rv, r2)
        r2 = r2.replace("not ", "!").replace("¬", "!").replace("!=", "≠")
        out.append(re.sub(r"\s+", "", r2))
    return "\n".join(sorted(out))


def find_duplicates(records: list[dict]) -> dict:
    by_triple: dict[str, list[str]] = defaultdict(list)
    by_cmd: dict[str, list[str]] = defaultdict(list)
    by_segment: dict[str, list[tuple[str, int]]] = defaultdict(list)
    by_program: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for r in records:
        ar = r["_arities"]
        order: dict[str, str] = {}
        tri = canon_text(r["pre"], ar, order) + "|" + canon_text(r["cmd"], ar, order) + "|" + canon_text(r["post"], ar, order)
        by_triple[tri].append(r["id"])
        by_cmd[canon_text(r["cmd"], ar, {})].append(r["id"])
        for i, seg in enumerate(r["_segments"], 1):
            if seg["loop"]:
                key = canon_text("\n".join(seg["lines"]), ar, {})
                by_segment[key].append((r["id"], i))
        for b in r["datalog"]:
            if b["provenance"].startswith(("fidelity", "check module", "production check", "the closure", "the program", "Soufflé", "hand-written")) or "legacy inventory" in b["provenance"]:
                rules = [l for l in b["text"].split("\n") if ":-" in l]
                if len(rules) >= 2:
                    by_program[canon_rules(rules)].append((r["id"], b["label"][:60]))
    triples = [ids for ids in by_triple.values() if len(ids) > 1]
    cmds = [ids for ids in by_cmd.values() if len(ids) > 1]
    segs = sorted([v for v in by_segment.values() if len({c for c, _ in v}) > 1], key=lambda v: (-len(v), v))
    progs = sorted([v for v in by_program.values() if len({c for c, _ in v}) > 1], key=lambda v: (-len(v), v))
    return {"triples": triples, "commands": cmds, "segments": segs, "programs": progs}


