def top_level_conjuncts(expr: str) -> list[str]:
    """Flatten an assertion into its top-level ∧-conjuncts (parenthesis aware)."""
    s = strip_parens(re.sub(r"\s+", " ", expr))
    parts, depth, cur, i = [], 0, "", 0
    while i < len(s):
        c = s[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        if depth == 0 and s.startswith("∧", i):
            parts.append(cur.strip())
            cur = ""
            i += 1
            continue
        cur += c
        i += 1
    parts.append(cur.strip())
    if len(parts) == 1:
        return [s]
    out: list[str] = []
    for p in parts:
        out.extend(top_level_conjuncts(p))
    return out


def strip_parens(s: str) -> str:
    s = s.strip()
    while s.startswith("(") and s.endswith(")"):
        try:
            inner, end = balanced(s, 0, "(", ")")
        except ValueError:
            break
        if end != len(s):
            break
        s = inner.strip()
    return s


def derive_kind(meta: dict, pre: str, post: str, cmdinfo: dict, arities: dict[str, int], witnesses: set[str]) -> str:
    if meta.get("kind"):
        return meta["kind"]
    conj = [strip_parens(c) for c in top_level_conjuncts(post)]
    if len(conj) == 1 and "∨" in conj[0]:
        return "conditional claim (implication)"
    flat = [c for c in conj if "∨" not in c]
    eq_any = [c for c in flat if re.search(r"(?<![≠<>])=(?!=)", c) and " ⊆ " not in c]
    contains = [c for c in flat if " ⊆ " in c]
    assigned = set(cmdinfo["assigned"])

    def side_names(expr: str) -> set[str]:
        return {snapshot_base(n) for n in names_in(expr, arities)}
    if witnesses:
        to_w = [c for c in contains if side_names(c.split(" ⊆ ", 1)[1]) <= witnesses and side_names(c.split(" ⊆ ", 1)[1])]
        w_below = [c for c in contains if side_names(c.split(" ⊆ ", 1)[0]) <= witnesses and side_names(c.split(" ⊆ ", 1)[0])]
        closure = [c for c in contains if c not in to_w and c not in w_below]
        if w_below and not to_w:
            return "equivalence (with a greatest fixpoint, via a post-fixpoint witness)"
        if to_w and (closure or eq_any):
            return "equivalence (with a least fixpoint, via a pre-fixpoint witness)"
        if to_w:
            return "containment (via a pre-fixpoint witness)"
    if eq_any and not contains:
        return "equivalence"
    if contains and not eq_any:
        comparisons = []
        for c in contains:
            l, r = c.split(" ⊆ ", 1)
            ln, rn = side_names(l), side_names(r)
            if ln and rn and (ln | rn) <= assigned and not (ln & rn):
                comparisons.append((frozenset(ln), frozenset(rn)))
        if comparisons and len(comparisons) == len(contains):
            if any((b, a) in comparisons for a, b in comparisons) or any(
                    a & b2 and b & a2 for (a, b) in comparisons for (a2, b2) in comparisons if (a, b) != (a2, b2)):
                return "equivalence (stated as mutual containments)"
            return "containment"
        return "correctness (closure/safety conditions on one program)"
    if contains and eq_any:
        return "correctness (closure conditions and an equality)"
    return "correctness"


def category_of(case: str, meta: dict) -> tuple[str, str]:
    key = CURATED["category_by_case"].get(case)
    if key is None:
        cat = meta.get("category")
        key = {"Synthetic": "synthetic", "LLM": "llm", "Production": "production", "Core": "verification-task",
               "Obstructed": "production"}.get(cat)
    if key is None or key not in CURATED["categories"]:
        return UNCATEGORIZED
    return key, CURATED["categories"][key]


