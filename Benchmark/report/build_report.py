def _load_sibling(name: str) -> object:
    """Load a sibling module by path, not by `sys.path` search: this script is sometimes
    loaded itself by path (e.g. by the tests, via `importlib.util.spec_from_file_location`),
    in which case a plain `import` of a module living next to it would not resolve."""
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod  # dataclasses on the loaded module resolve `cls.__module__` here
    spec.loader.exec_module(mod)
    return mod


