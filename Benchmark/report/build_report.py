def emitter_wrote(path: Path) -> bool:
    """True when the file exists and its first line is the certificate emitter's marker."""
    if not path.exists():
        return False
    with path.open(encoding="utf-8") as f:
        return f.readline().rstrip("\n") in EMITTER_MARKERS


def status_of(case: str) -> str:
    """What the case folder itself shows, independent of what its metadata claims.

    A certificate outranks the record it was built from, so a certified case keeps its
    certified status although its record stands beside it. A record with no certificate is a
    solved case: the answer is known and frozen, and nothing has been kernel-checked yet.
    """
    folder = CASES_DIR / case
    cert = folder / "Certificate"
    if emitter_wrote(cert / "Valid.lean"):
        return "certified valid"
    if emitter_wrote(cert / "Invalid.lean"):
        return "certified invalid"
    if (folder / CORE_RECORD).exists():
        return SOLVED_VALID
    if (folder / COUNTEREXAMPLE_RECORD).exists():
        return SOLVED_INVALID
    return "open"


def load_placement() -> dict[str, dict]:
    """The generated certificate placement ledger, or nothing when there is none.

    Benchmark/CertificatePlacement.json is machine state: the placement script measures every
    emitter-written certificate under the watched build's memory limit and records, per case, a
    digest of the certificate tree, the peak resident memory its kernel check reached, whether
    that fits and, when it does not, the note saying so. An absent file, or an absent entry,
    means the certificate is checked inside the library build like any other.
    """
    path = CASES_DIR / PLACEMENT_FILE
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as error:
        die(f"{PLACEMENT_FILE}: {error}")
    if not isinstance(data, dict) or data.get("version") not in PLACEMENT_VERSIONS:
        die(f"{PLACEMENT_FILE} is not one of versions "
            + ", ".join(str(v) for v in PLACEMENT_VERSIONS))
    entries = data.get("certificates")
    if not isinstance(entries, dict):
        die(f"{PLACEMENT_FILE} has no certificates object")
    for case, entry in entries.items():
        if not isinstance(entry, dict) or not isinstance(entry.get("fits"), bool):
            die(f"{PLACEMENT_FILE}: malformed entry for {case}")
    return entries


PLACEMENT = load_placement()


def placement_of(case: str, placement: dict[str, dict] | None = None) -> tuple[bool, str]:
    """(checked outside the library build, the ledger's note) for one case."""
    entry = (PLACEMENT if placement is None else placement).get(case)
    if not entry or entry.get("fits", True):
        return False, ""
    return True, str(entry.get("note") or "")


def placement_peak_kb(case: str, placement: dict[str, dict] | None = None) -> int | None:
    """The peak resident memory the ledger measured for the case, when it measured one.

    A ledger written before the peak was recorded carries none, and so does a case the ledger
    does not name; both read as None, and the report then says nothing about a peak.
    """
    entry = (PLACEMENT if placement is None else placement).get(case) or {}
    peak = entry.get("peakKb")
    if isinstance(peak, bool) or not isinstance(peak, int) or peak < 0:
        return None
    return peak


def placement_peak_text(peak_kb: int | None) -> str:
    """How the report names a measured peak beside the placement note, in whole megabytes."""
    return f" (peak {peak_kb // 1024} MB)" if peak_kb else ""


def case_status_text(rec: dict) -> str:
    """The status as a case's own section prints it.

    It is the status the folder shows, widened by the reason the certificate is not in the
    library build when the placement ledger says so. The status summary counts the plain
    status, so a case certified outside the library build counts as certified there like any
    other.
    """
    if rec.get("certificate_outside_library"):
        return f"{rec['status']} ({OUTSIDE_LIBRARY_SUFFIX})"
    return rec["status"]


def expectation_of(meta: dict) -> str:
    """The verdict the case's metadata expects, under whichever of the two field names it uses."""
    for key in ("expectedVerdict", "currentClassification"):
        v = meta.get(key)
        if v:
            return str(v)
    return "none recorded"


def sources_of(case: str, meta: dict) -> list[dict]:
    out: list[dict] = []
    for s in meta.get("sources") or []:
        if "url" in s:
            label = s.get("title") or " ".join(x for x in [s.get("system"), s.get("repo"), s.get("file"), s.get("function")] if x)
            detail = "; ".join(x for x in [
                f"branch {s['branch']}" if s.get("branch") else None,
                f"commit {s['commit']}" if s.get("commit") else None,
                f"sections {s['sections']}" if s.get("sections") else None,
                f"read {s['read']}" if s.get("read") else None,
                s.get("encodedAs") and f"encoded as {s['encodedAs']}"] if x)
            out.append({"label": label, "url": s.get("url"), "detail": detail})
    for key in CURATED["sources_by_case"].get(case, []):
        link = CURATED["source_links"][key]
        out.append({"label": link["label"], "url": link["url"], "detail": ""})
    if meta.get("sourceProgram"):
        out.append({"label": f"program source file {meta['sourceProgram']}", "url": None, "detail": ""})
    for side in meta.get("sides") or []:
        if side.startswith("Examples/"):
            out.append({"label": f"side translation {side}", "url": None, "detail": ""})
    # dedupe by (label,url)
    seen, res = set(), []
    for s in out:
        k = (s["label"], s["url"])
        if k not in seen:
            seen.add(k)
            res.append(s)
    return res


def compute_tags(case: str, parsed: dict, cmdinfo: dict, meta: dict, blocks: list[dict], witnesses: set[str]) -> tuple[list[str], dict]:
    """Auto tags (nonlinear-recursion, mutual-recursion, negation) from the Datalog rules and the
    Whiel text; the remaining tags come from curated.json and the prophecy status lists."""
    t: set[str] = set()
    pre, cmd, post = parsed["pre"], parsed["cmd"], parsed["post"]
    rules_all = [r for b in blocks for r in b["text"].split("\n") if ":-" in r]
    ra = analyze_rules(rules_all) if rules_all else {"negation": False, "inequality": False, "mutual": False, "nonlinear": False}
    if "∖" in pre or "∖" in post or ra["negation"]:
        t.add("negation")
    if ra["nonlinear"] or cmdinfo["nonlinear_ra"]:
        t.add("nonlinear-recursion")
    if ra["mutual"]:
        t.add("mutual-recursion")
    if witnesses:
        t.add("fixpoint-witness")
    if cmdinfo["frontier"]:
        t.add("semi-naive")
    for m in CURATED["manual_tags"].get(case, []):
        t.add(m)
    if any(case in CURATED["prophecy_status"][k] for k in PROPHECY_LISTS):
        t.add("prophecy")
    unknown = [x for x in t if x not in VOCAB]
    if unknown:
        die(f"{case}: tags not in tags.json: {unknown}")
    return sorted(t), ra


