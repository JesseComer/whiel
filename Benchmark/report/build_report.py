def balanced(text: str, start: int, open_ch: str, close_ch: str) -> tuple[str, int]:
    """text[start] must be open_ch; return (inner text, index after the closer)."""
    assert text[start] == open_ch, (text[start:start + 20])
    depth = 0
    i = start
    while i < len(text):
        c = text[i]
        if c == open_ch:
            depth += 1
        elif c == close_ch:
            depth -= 1
            if depth == 0:
                return text[start + 1:i], i + 1
        i += 1
    raise ValueError("unbalanced")


def macro_body(text: str, decl: str) -> str:
    i = text.find(decl)
    if i < 0:
        raise ValueError(f"missing {decl}")
    j = text.find("![", i)
    inner, _ = balanced(text, j + 1, "[", "]")
    return inner


def dedent(block: str) -> str:
    lines = block.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    indents = [len(l) - len(l.lstrip()) for l in lines if l.strip()]
    cut = min(indents) if indents else 0
    return "\n".join(l[cut:] if l.strip() else "" for l in lines)


CONTRIBUTOR_HEADER = "-- Benchmark contributors:"


def parse_input(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.search(r"/-(.*?)-/", text, re.S)
    header = dedent(m.group(1)) if m else ""
    first = text.split("\n", 1)[0]
    contributors = first[len(CONTRIBUTOR_HEADER):].strip() if first.startswith(CONTRIBUTOR_HEADER) else ""
    legacy = "whielSch!" in text
    schema_body = macro_body(text, "def programSchema" if legacy else "def inputSchema")
    arities: dict[str, int] = {}
    for group, ar in re.findall(r"\{([^}]*)\}\s*\(arity:\s*(\d+)\)", schema_body):
        for name in group.split(","):
            name = name.strip()
            if name:
                arities[name] = int(ar)
    pre = dedent(macro_body(text, "def inputPre"))
    post = dedent(macro_body(text, "def inputPost"))
    cmd_macro = macro_body(text, "def inputCmd")
    k = cmd_macro.find("ExecSchema")
    k = cmd_macro.find("}", k) + 1
    k = cmd_macro.find("{", k)
    cmd_inner, _ = balanced(cmd_macro, k, "{", "}")
    cmd = dedent(cmd_inner)
    return {
        "header": header,
        "contributors": contributors,
        "notation": "legacy" if legacy else "canonical",
        "arities": arities,
        "pre": pre,
        "cmd": cmd,
        "post": post,
    }


IDENT = re.compile(r"(?<![#\w])[A-Za-z_][A-Za-z0-9_]*")
KEYWORDS = {"WHILE", "DO", "END", "IF", "THEN", "ELSE", "true", "false", "arity"}


def names_in(text: str, arities: dict[str, int]) -> set[str]:
    return {w for w in IDENT.findall(text) if w in arities}


def snapshot_base(name: str) -> str:
    return re.sub(r"_(aux|2)$", "", name)


def analyze_cmd(cmd: str, arities: dict[str, int]) -> dict:
    """Assignments, reads, top-level loop segments, nesting, guard kinds, dependent phases."""
    lines = cmd.split("\n")
    assigned: list[str] = []
    reads: set[str] = set()
    depth = 0
    max_depth = 0
    # a segment = the assignments before a top-level loop + that loop; trailing assignments form a loop-free segment
    segments: list[dict] = []
    cur = {"lines": [], "prefix_assigned": set(), "prefix_reads": set(), "body_assigned": set(), "body_reads": set(), "loop": False, "guards": []}
    guards: list[str] = []
    nonlinear = False
    loop_bodies: list[list[str]] = []
    for line in lines:
        st = line.strip()
        if st.startswith("WHILE"):
            depth += 1
            max_depth = max(max_depth, depth)
            g = st[len("WHILE"):]
            g = g[: g.rfind("DO")] if "DO" in g else g
            g = g.strip()
            guards.append(g)
            cur["guards"].append(g)
            cur["loop"] = True
            reads |= names_in(g, arities)
            cur["body_reads"] |= names_in(g, arities)
            loop_bodies.append([])
        elif st.startswith("END"):
            depth -= 1
            body = loop_bodies.pop()
            if depth == 0:
                cur["lines"].append(line)
                cur["body_lines"] = body
                segments.append(cur)
                cur = {"lines": [], "prefix_assigned": set(), "prefix_reads": set(), "body_assigned": set(), "body_reads": set(), "loop": False, "guards": []}
                continue
            else:
                loop_bodies[-1].extend(body)
        elif ":=" in st:
            lhs, rhs = st.split(":=", 1)
            lhs = lhs.strip()
            assigned.append(lhs)
            r = names_in(rhs, arities)
            reads |= r
            if depth > 0:
                cur["body_assigned"].add(lhs)
                cur["body_reads"] |= r
                loop_bodies[-1].append(st)
                for a, b in re.findall(r"\(\s*(\w+)\s*×\s*(\w+)\s*\)", rhs):
                    if snapshot_base(a) == snapshot_base(b) and snapshot_base(a) in arities:
                        nonlinear = True
            else:
                cur["prefix_assigned"].add(lhs)
                cur["prefix_reads"] |= r
        else:
            r = names_in(st, arities)
            reads |= r
            if depth > 0:
                cur["body_reads"] |= r
                if loop_bodies:
                    loop_bodies[-1].append(st)
            else:
                cur["prefix_reads"] |= r
        cur["lines"].append(line)
    if cur["lines"]:
        cur["body_lines"] = []
        segments.append(cur)
    # dependent phases: a loop's body/guard, or the prefix assignments feeding it, read a relation
    # computed by an earlier loop (output-copy assignments after a loop do not count)
    dependent = False
    earlier: set[str] = set()
    for seg in segments:
        if seg["loop"]:
            needed = {snapshot_base(x) for x in seg["body_reads"]}
            prefix_lines = [l.strip() for l in seg["lines"] if ":=" in l and not l.strip().startswith("WHILE")]
            prefix_lines = prefix_lines[: len(seg["prefix_assigned"])] if seg["prefix_assigned"] else []
            changed = True
            while changed:
                changed = False
                for pl in prefix_lines:
                    lhs, rhs = pl.split(":=", 1)
                    if snapshot_base(lhs.strip()) in needed:
                        for n in names_in(rhs, arities):
                            if snapshot_base(n) not in needed:
                                needed.add(snapshot_base(n))
                                changed = True
            if needed & earlier:
                dependent = True
            earlier |= {snapshot_base(x) for x in seg["prefix_assigned"] | seg["body_assigned"]}
        seg["assigned"] = seg["prefix_assigned"] | seg["body_assigned"]
        seg["reads"] = seg["prefix_reads"] | seg["body_reads"]
    top_loops = sum(1 for seg in segments if seg["loop"])
    frontier = any(re.search(r"≠\s*∅", g) or re.search(r"¬\s*\(.*=\s*∅\s*\)", g) for g in guards)
    naive = False
    for seg in segments:
        if not seg["loop"]:
            continue
        body = "\n".join(seg.get("body_lines", []))
        for g in seg["guards"]:
            for gg in re.split(r"\s*∨\s*", g.strip("() ")):
                m = re.match(r"\(?\s*(\w+)\s*≠\s*(\w+)\s*\)?$", gg.strip()) or re.match(r"¬\s*\(\s*(\w+)\s*=\s*(\w+)\s*\)$", gg.strip())
                if m:
                    a, b = m.group(1), m.group(2)
                    if b == "∅" or a == "∅":
                        continue
                    if re.search(rf"\b{re.escape(a)}\s*:=\s*{re.escape(b)}\b", body) or re.search(rf"\b{re.escape(b)}\s*:=\s*{re.escape(a)}\b", body):
                        naive = True
    set_difference = "∖" in cmd
    return {
        "assigned": sorted(set(assigned)),
        "reads": sorted(reads),
        "segments": segments,
        "top_loops": top_loops,
        "nested": max_depth >= 2,
        "dependent": dependent,
        "frontier": frontier,
        "naive": naive,
        "set_difference": set_difference,
        "nonlinear_ra": nonlinear,
        "guards": guards,
    }


