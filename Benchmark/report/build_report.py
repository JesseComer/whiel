def main() -> None:
    records = build_records()
    if not records:
        die("no cases found")
    dups = find_duplicates(records)
    # JSON inventory (drop private keys). No build date: the file must depend only on the corpus.
    inv = [{k: v for k, v in r.items() if not k.startswith("_")} for r in records]
    (HERE / "inventory.json").write_text(json.dumps({"count": len(inv), "duplicates": dups, "entries": inv},
                                                    ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    tex = build_tex(records, dups)
    (HERE / "benchmark_report.tex").write_text(tex, encoding="utf-8")
    (HERE / "benchmark_report.html").write_text(build_html(records, dups), encoding="utf-8")
    build_sheets(records)
    if UNKNOWN_CHARS:
        print("characters replaced by '?' in the PDF:", dict(UNKNOWN_CHARS))
    if "--no-pdf" not in sys.argv:
        env = dict(os.environ, SOURCE_DATE_EPOCH="0", FORCE_SOURCE_DATE="1")
        for _ in range(2):
            p = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "benchmark_report.tex"],
                               cwd=HERE, capture_output=True, env=env)
            if p.returncode != 0:
                tail = p.stdout.decode("utf-8", errors="replace")[-3000:]
                die("pdflatex failed:\n" + tail)
        for ext in (".aux", ".out", ".toc", ".log"):
            f = HERE / f"benchmark_report{ext}"
            if f.exists():
                f.unlink()
    counts = Counter(t for r in records for t in r["tags"])
    print(f"{len(records)} cases; status: " + ", ".join(f"{s} {n}" for s, n in status_counts(records)))
    print(f"duplicate scan (console only, also in inventory.json): alpha-equivalent triples={dups['triples'] or 'none'}; "
          f"same command with a different claim={dups['commands'] or 'none'}")
    print("tag counts:", dict(sorted(counts.items(), key=lambda kv: -kv[1])))
    print("unused tags:", [t for t in VOCAB if counts[t] == 0])
    print("kinds:", dict(Counter(r["kind"] for r in records)))


if __name__ == "__main__":
    main()
