def latex_escape(text: str) -> str:
    text = str(text)
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
            "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}"}
    out = []
    for ch in text:
        if ch in repl:
            out.append(repl[ch])
        elif ord(ch) < 128 or ch in UNICODE or ch in LATIN_OK:
            out.append(ch)
        elif ch in TEXT_UNICODE:
            out.append(TEXT_UNICODE[ch])
        else:
            UNKNOWN_CHARS[ch] += 1
            out.append("?")
    return "".join(out)


def text_with_paths(text: str) -> str:
    """latex_escape, but tokens that look like file paths are set with \\path{} so they can break."""
    out = []
    for tok in str(text).split(" "):
        core, tail = tok, ""
        while core and core[-1] in ",;.:)":
            tail = core[-1] + tail
            core = core[:-1]
        if "/" in core and not core.startswith("http") and len(core) > 8 and not core.startswith("("):
            out.append(r"\path{" + sanitize_verbatim(core).replace("{", "").replace("}", "") + "}" + latex_escape(tail))
        else:
            out.append(latex_escape(tok))
    return " ".join(out)


